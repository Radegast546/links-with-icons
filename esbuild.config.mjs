import esbuild from 'esbuild';
import process from 'process';
import { builtinModules } from 'module';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const projectDir = path.dirname(fileURLToPath(import.meta.url));
const production = process.argv.includes('production');
const deploy = process.argv.includes('--deploy');
const deployDirectory = process.env.OBSIDIAN_PLUGIN_DIR;

if (deploy && !deployDirectory) {
    throw new Error('Set OBSIDIAN_PLUGIN_DIR before running npm run deploy.');
}

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const copyToVaultPlugin = {
    name: 'copy-to-vault',
    setup(build) {
        build.onEnd((result) => {
            if (!deploy || result.errors.length > 0) return;

            fs.mkdirSync(deployDirectory, { recursive: true });
            for (const filename of ['main.js', 'manifest.json', 'styles.css']) {
                fs.copyFileSync(path.join(projectDir, filename), path.join(deployDirectory, filename));
            }
            console.log(`Deployed plugin files to ${deployDirectory}`);
        });
    },
};

const context = await esbuild.context({
    banner: { js: banner },
    entryPoints: [path.join(projectDir, 'main.ts')],
    bundle: true,
    external: [
        'obsidian',
        'electron',
        '@codemirror/autocomplete',
        '@codemirror/collab',
        '@codemirror/commands',
        '@codemirror/language',
        '@codemirror/lint',
        '@codemirror/search',
        '@codemirror/state',
        '@codemirror/view',
        '@lezer/common',
        '@lezer/highlight',
        '@lezer/lr',
        ...builtinModules,
    ],
    format: 'cjs',
    target: 'es2018',
    logLevel: 'info',
    sourcemap: production ? false : 'inline',
    treeShaking: true,
    outfile: path.join(projectDir, 'main.js'),
    plugins: [copyToVaultPlugin],
});

if (production) {
    await context.rebuild();
    await context.dispose();
} else {
    await context.watch();
}
